const DICT: Record<Lang, Partial<Dict>> = { en, hi, mr };

export type StringKey = keyof Dict;

/** Translate with automatic fallback to the default (English) language. */
export function makeT(lang: Lang) {
  return (key: StringKey): string => DICT[lang]?.[key] ?? en[key];
}

/** Pick a localized field from a content record, falling back to English. */
export function loc<T extends { name?: string; nameHi?: string | null; nameMr?: string | null }>(
  lang: Lang,
  item: T,
): string {
  if (lang === "hi") return item.nameHi || item.name || "";
  if (lang === "mr") return item.nameMr || item.nameHi || item.name || "";
  return item.name || "";
}

export function locTitle(
  lang: Lang,
  item: { title: string; titleHi?: string | null; titleMr?: string | null },
): string {
  if (lang === "hi") return item.titleHi || item.title;
  if (lang === "mr") return item.titleMr || item.titleHi || item.title;
  return item.title;
}
